import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';

const source = fs.readFileSync('src/lib/navigation-route.ts', 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const module = { exports: {} };
vm.runInThisContext(`(function(module,exports){${compiled}\n})`, { filename: 'navigation-route.ts' })(module, module.exports);
const { validRoutePoint, itineraryFingerprint, routeDistanceMeters, nearestRouteProgress, normalizeOsrmRoute, normalizeGoogleRoute, normalizeValhallaRoute, routeGuidance } = module.exports;
const a = { lat: 16.468, lng: 107.579 }, b = { lat: 16.472, lng: 107.588 };
const snapshot = itineraryFingerprint({ days: [{ activities: [a, b] }] });
assert.equal(validRoutePoint({ lat: 0, lng: 0 }), null);
assert.equal(validRoutePoint({ lat: 'bad', lng: 107.58 }), null);
assert.ok(routeDistanceMeters(a, b) > 900);
assert.notEqual(snapshot, itineraryFingerprint({ days: [{ activities: [b, a] }] }));
const progress = nearestRouteProgress([a, b], { lat: 16.47, lng: 107.584 });
assert.ok(progress.fraction > 0 && progress.fraction < 1);
assert.ok(nearestRouteProgress([a, b], { lat: 16.6, lng: 107.8 }).offRouteMeters > 1000);
const osrm = normalizeOsrmRoute({ code: 'Ok', routes: [{ geometry: { coordinates: [[a.lng, a.lat], [b.lng, b.lat]] }, distance: 1200, duration: 900, legs: [{ steps: [{ distance: 100, name: 'Trần Hưng Đạo', maneuver: { type: 'turn', modifier: 'left', location: [a.lng, a.lat] } }] }] }] }, a, b, 1, snapshot);
assert.equal(osrm.provider, 'osrm_preview');
assert.equal(osrm.durationSeconds, 960);
assert.equal(osrm.steps[0].instruction, 'Rẽ trái vào Trần Hưng Đạo');
assert.equal(osrm.points[0].lat, a.lat);
assert.equal(normalizeOsrmRoute({ code: 'NoRoute' }, a, b, 1, snapshot), null);
assert.equal(normalizeOsrmRoute({ code: 'Ok', routes: [{ geometry: { coordinates: [] }, distance: 1200, duration: 900, legs: [] }] }, a, b, 1, snapshot), null);
const google = normalizeGoogleRoute({ routes: [{ polyline: { geoJsonLinestring: { coordinates: [[a.lng, a.lat], [b.lng, b.lat]] } }, distanceMeters: 1300, duration: '960s', legs: [{ steps: [{ distanceMeters: 150, navigationInstruction: { instructions: 'Rẽ vào đường Bạch Đằng' }, startLocation: { latLng: { latitude: a.lat, longitude: a.lng } } }] }] }] }, a, b, 1, 'WALK', snapshot);
assert.equal(google.provider, 'google');
assert.equal(google.durationSeconds, 960);
assert.equal(google.steps[0].instruction, 'Rẽ vào đường Bạch Đằng');
console.log('PASS navigation route: coordinate bounds, fingerprint, progress, OSRM and Google normalization, invalid route');
const valhalla = normalizeValhallaRoute({ code: 'Ok', routes: [{ geometry: { coordinates: [[a.lng, a.lat], [b.lng, b.lat]] }, distance: 1200, duration: 850, legs: [{ steps: [{ distance: 600, maneuver: { type: 'depart', location: [a.lng, a.lat] } }, { distance: 600, name: 'Trần Hưng Đạo', maneuver: { type: 'turn', modifier: 'right', location: [b.lng, b.lat] } }] }] }] }, a, b, 1, snapshot);
assert.equal(valhalla.provider, 'valhalla');
assert.equal(valhalla.durationSeconds, 850);
const guidance = routeGuidance(valhalla, a);
assert.equal(guidance.instruction, 'Bắt đầu đi');
assert.equal(guidance.nextInstruction, 'Rẽ phải vào Trần Hưng Đạo');
assert.ok(guidance.turnMeters > 900);
assert.ok(routeGuidance(valhalla, b).remainingMeters < 1);
console.log('PASS Valhalla pedestrian duration and single maneuver guidance');
